fn main() {
    let mut s = String::from("Привет");

    // Несколько неизменяемых ссылок одновременно — это нормально
    let a = &s;
    let b = &s;

    // Но пока есть a и b, мы не можем создать изменяемую ссылку
    // let c = &mut s; // ошибка компиляции
    println!("{a}, {b}");

    // После того как a и b больше не используются, можно создать &mut
    let c = &mut s;
    c.push_str(", мир!");
    println!("{c}");
}
