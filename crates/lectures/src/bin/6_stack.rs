// Вернуть из функции локальное значение, можно только саллоцировав его
// в куче. В Go это происходит автоматически, так как в язык встроен рантайм,
// управляющий памятью через подсчет ссылок. В Rust мы должны сделать это явно,
// применив очередной умный указатель - `Box`, который аллоцирует переданное
// значение в куче. При этом, подсчет ссылок не используется, а для освобождения
// памяти применяется стандартный механизм Borrow Checker - когда значение
// покинет последнюю область видимости, реализация `Drop` для `Box`
// деаллоцирует значение.
fn get_ref() -> Box<i32> {
    let num = 42;
    Box::new(num)
}

fn nested(ref_u32: &i32) {
    println!("Вложеный указатель: {}", *ref_u32);
}

fn use_ref(ref_u32: &i32) {
    println!("Вложеный указатель: {}", *ref_u32);
    nested(ref_u32);
}

fn main() {
    let num = 69;
    use_ref(&num);

    let num_ref = get_ref();
    println!("Число из указателя: {}", *num_ref);
}
